import { describe, expect, it } from 'vitest'
import { readFileSync } from 'node:fs'

const read = (path: string) => readFileSync(new URL(`../${path}`, import.meta.url), 'utf8')

describe('workbench dark theme', () => {
  it('uses one chrome surface and one editor surface', () => {
    const styles = read('src/client/styles.ts')
    expect(styles).toContain('--dvw-base:#191a1b')
    expect(styles).toContain('--dvw-surface-1:#121314')
    expect(styles).toContain('--dvw-surface-2:#202122')
    expect(styles).toContain('--dvw-side:#191a1b')
    expect(styles).toContain('--dvw-accent:#307e9f')
    expect(styles).toContain('.dvw-side{grid-column:2;grid-row:1/3;min-width:0;width:100%;background:var(--dvw-side)')
    expect(styles).toContain('.dvw-status{grid-column:1/4;grid-row:3;background:var(--dvw-base);color:var(--dvw-text);display:flex;align-items:center;padding:6px 8px 0;')
    expect(read('src/client/Workbench.tsx')).toContain("body.toggleAttribute('data-ds-dark-theme',theme==='dark')")
    expect(read('src/client/Workbench.tsx')).toContain('data-dvw-theme={colorScheme}')
    expect(read('src/client/Workbench.tsx')).toContain('followDsh={false}')
    expect(styles).toContain('body[data-dvw-palette=dark] [data-dvw-conversation-panel]')
  })

  it('keeps only one explorer row highlighted at a time', () => {
    const styles = read('src/client/styles.ts')
    expect(styles).toContain(
      '.dvw-tree:has(.dvw-tree-row:hover) .dvw-tree-row[data-selected=true]:not(:hover){background:transparent}'
    )
  })

  it('offers the workbench from the sidebar panel list', () => {
    const index = read('src/client/index.tsx')
    expect(index).toContain("export const inject = ['slots', 'layout', 'remote', 'remote.terminal', 'sidebarRight', 'sidebarRightTabs']")
    expect(index).toContain("name: 'sidebar.panellist'")
    expect(index).toContain("label: () => 'VS Code 工作台'")
    expect(index).not.toContain('sidebar.footer.action')
    expect(read('src/client/DshConversationPanel.tsx')).toContain("body.setAttribute('data-dvw-palette', colorScheme)")
  })

  it('keeps the DSH chat toggle in the activity bar', () => {
    const workbench = read('src/client/Workbench.tsx')
    expect(workbench).toContain("label:chatVisible?'关闭 DSH 对话栏 (Ctrl+Alt+B)':'显示 DSH 对话栏 (Ctrl+Alt+B)'")
    expect(workbench).not.toContain('dvw-chat-toggle')
  })

  it('uses VS Code tabs, activity selection and middle-click close', () => {
    const styles = read('src/client/styles.ts')
    const workbench = read('src/client/Workbench.tsx')
    expect(styles).toContain('.dvw-act .codicon,.dvw-activity-ghost .codicon{font-size:20px!important}')
    expect(styles).toContain('.dvw-activity{grid-row:1/3;background:var(--dvw-base);border:1px solid var(--dvw-border);border-radius:8px 0 0 8px;')
    expect(styles).toContain('.dvw-act[data-active=true]::before{background:var(--dvw-tab-active)}')
    expect(styles).toContain('.dvw-tab[data-active=true]{background:var(--dvw-surface-1)')
    expect(styles).toContain('--dvw-tab-active:#e8e8e8')
    expect(workbench).toContain('<DshMark size={22}/>')
    expect(styles).toContain('.dvw-tab{border-radius:10px 10px 0 0;border-right:0}')
    expect(styles).toContain('.dvw-tab[data-active=true]::before,.dvw-tab[data-active=true]::after{content:"";position:absolute;bottom:0;width:10px;height:10px;background:var(--dvw-surface-1);pointer-events:none}')
    expect(styles).toContain('clip-path:path("M10 0C10 5.5 5.5 10 0 10L10 10Z")')
    expect(styles).toContain('clip-path:path("M0 0C0 5.5 4.5 10 10 10L0 10Z")')
    expect(styles).toContain('.dvw-tab:hover:not([data-active=true]){background:color-mix(in srgb,var(--dvw-text) 3%,transparent)}')
    expect(read('src/client/MonacoEditor.tsx')).toContain("'vs/nls': { availableLanguages: { '*': 'zh-cn' } }")
    expect(read('src/client/MonacoEditor.tsx')).toContain("'vs/nls.messages.zh-cn'")
    expect(workbench).toContain('dvw-bottom-reveal')
    expect(workbench).toContain('startHeight+startY-e.clientY<80')
    expect(workbench).toContain("onAuxClick={event=>{if(event.button===1){event.preventDefault();close(tab)}}}")
  })

  it('offers a branch picker in source control', () => {
    const workbench = read('src/client/Workbench.tsx')
    const styles = read('src/client/styles.ts')
    expect(workbench).toContain('dvw-branch-menu')
    expect(workbench).toContain("action:'branch.switch'")
    expect(workbench).toContain("action:'branch.create'")
    expect(workbench).toContain("action:'branch.list'")
    expect(workbench).toContain('dvw-branch-worktree')
    expect(workbench).toContain('dvw-branch-error-message')
    expect(workbench).toContain('无法切换分支')
    expect(workbench).toContain('setBranchError(branchErrorMessage(error))')
    expect(styles).toContain('.dvw-confirm .dvw-branch-error-message{')
    expect(workbench).toContain('新分支名称')
    expect(styles).toContain('.dvw-branch-menu{')
  })

  it('keeps the explorer loaded when switching sessions in one workspace', () => {
    expect(read('src/client/index.tsx')).toContain("key={cwd ?? 'no-workspace'}")
    expect(read('src/client/Workbench.tsx')).toContain('loadedWorkspaceCwd.current === cwd')
  })

  it('offers a centered workspace switcher below the DSH conversation button', () => {
    const workbench = read('src/client/Workbench.tsx')
    expect(workbench).toContain('打开工作区 / 切换会话')
    expect(workbench).toContain('<WorkspaceSwitcher choices={switcherChoices}')
    expect(workbench).toContain("api<{opened:boolean;workspace?:{id:string}}>('workspace.open'")
    expect(read('src/client/index.tsx')).toContain('createDshNavigation(')
    expect(read('src/index.ts')).toContain("ctx.inject(['directoryPicker', 'workspaceRegistry']")
  })

  it('matches the settings modal surface for the workspace switcher', () => {
    const styles = read('src/client/styles.ts')
    const switcher = read('src/client/WorkspaceSwitcher.tsx')
    expect(switcher).toContain('createPortal(')
    expect(switcher).toContain('className="dvw-workspace-backdrop"')
    expect(switcher).toContain('className="dvw-overlay dvw-workspace-layer"')
    expect(styles).toContain('.dvw-workspace-layer{position:fixed!important;inset:0!important;z-index:1000!important;')
    expect(styles).toContain('.dvw-workspace-backdrop{position:absolute;inset:0;z-index:50;display:grid;place-items:center;padding:24px;background:rgba(0,0,0,.34);backdrop-filter:blur(3px)}')
    expect(styles).toContain('.dvw-workspace-switcher{width:min(640px,calc(100vw - 48px));height:min(680px,calc(100vh - 48px));max-height:none;border-radius:18px;')
    expect(styles).toContain('.dvw-workspace-switcher>footer button.dvw-primary-button:hover:not(:disabled){background:color-mix(in srgb,var(--dvw-accent) 86%,#000)}')
  })

  it('shows the explorer file icons in the Git change list', () => {
    const workbench = read('src/client/Workbench.tsx')
    expect(workbench).toContain("<FileIcon name={change.path.split('/').at(-1) ?? change.path}/>")
    expect(workbench).not.toContain("change.untracked?'new-file':'diff'")
  })

  it('opens search results at the matched line with a highlight', () => {
    const workbench = read('src/client/Workbench.tsx')
    expect(workbench).toContain('props.onOpen(path,row.line,row.column,row.match||query)')
    expect(workbench).toContain('highlight={activeTab.highlight}')
    expect(read('src/client/MonacoEditor.tsx')).toContain("inlineClassName: 'dvw-search-hit'")
    expect(read('src/client/styles.ts')).toContain('.dvw-search-hit{')
  })

  it('offers VS Code tab close actions from the context menu', () => {
    const workbench = read('src/client/Workbench.tsx')
    const styles = read('src/client/styles.ts')
    expect(workbench).toContain('onContextMenu={event=>{event.preventDefault();setBrowserId(undefined);setDshTabActive(false);setActive(tab.path);setTabMenu(')
    expect(workbench).toContain('dvw-tab-menu')
    expect(workbench).toContain('关闭其他')
    expect(workbench).toContain('关闭右侧标签页')
    expect(workbench).toContain('关闭已保存')
    expect(workbench).toContain('全部关闭')
    expect(workbench).not.toContain('dvw-close-all')
    expect(styles).toContain('.dvw-tab-menu{min-width:220px}')
  })

  it('uses VS Code light surfaces and separators', () => {
    const styles = read('src/client/styles.ts')
    expect(styles).toContain('--dvw-base:#f9fafb')
    expect(styles).toContain('--dvw-side:#f9fafb')
    expect(styles).toContain('--dvw-gutter:#f9fafb')
    expect(styles).toContain('--dvw-border:#e5e5e5')
    expect(styles).toContain('border-left:1px solid var(--dvw-border);border-top:1px solid var(--dvw-border);border-right:1px solid var(--dvw-border);border-bottom:1px solid var(--dvw-border);border-radius:8px;margin-left:3px;overflow:hidden}')
    expect(styles).not.toContain('.dvw-overlay[data-dvw-bottom-panel] .dvw-main')
    expect(styles).toContain('.dvw-tabs[data-empty]{display:none}')
    expect(read('src/client/Workbench.tsx')).toContain('data-empty={(tabs.length===0&&dshPanelId===undefined&&browserTabs.length===0)||undefined}')
    expect(read('src/client/Workbench.tsx')).toContain('data-dvw-bottom-panel={snapshot.bottomPanel||undefined}')
    expect(styles).toContain('.dvw-bottom{grid-column:3;grid-row:2;height:260px;min-height:120px;border-top:1px solid var(--dvw-border);border-left:1px solid var(--dvw-border);border-right:1px solid var(--dvw-border);border-bottom:1px solid var(--dvw-border);border-radius:8px;margin-top:4px;margin-left:3px')
    expect(styles).toContain('.dvw-tabs{height:35px;background:linear-gradient(to top,var(--dvw-border) 0 1px,var(--dvw-base) 1px 100%)')
    expect(styles).toContain('.dvw-tabs{background:color-mix(in srgb,var(--dvw-text) 4%,var(--dvw-base))}')
    expect(styles).toContain('border-top:1px solid var(--dvw-border);border-bottom:1px solid var(--dvw-border);border-right:1px solid var(--dvw-border);border-top-right-radius:8px;border-bottom-right-radius:8px;overflow:hidden')
    expect(styles).toContain('padding-top:calc(var(--dvw-titlebar-height) + 6px)')
    expect(styles).toContain('html[data-windows-titlebar] .dvw-overlay{top:var(--dvw-titlebar-height);padding-top:6px}')
    expect(styles).toContain('.dvw-overlay:not([data-dvw-primary-side=true]) .dvw-activity{border-radius:8px}')
    expect(styles).not.toContain('.dvw-status{grid-column:1/4;grid-row:3;background:var(--dvw-base);color:var(--dvw-text);border-top')
    expect(styles).toContain('[data-dvw-conversation-panel]{position:fixed!important;top:calc(var(--dvw-titlebar-height) + 6px)!important;right:3px!important;bottom:var(--dvw-status-height,30px)!important')
    expect(read('src/client/Workbench.tsx')).toContain('statusHeight={statusVisible?30:6}')
    expect(styles).toContain('body[data-dvw-palette=light] [data-dvw-conversation-panel]{--dsw-alias-bg-base:#f9fafb;--dsw-specific-sidebar-fill:#f9fafb;--dsw-alias-border-l2:#e5e5e5;background:#f9fafb!important}')
    expect(styles).toContain('.dvw-tabs{height:35px')
    expect(styles).toContain('.dvw-tab{position:relative;height:35px')
    expect(styles).toContain('.dvw-tree-row{display:flex;align-items:center;height:22px;')
    expect(styles).toContain('.dvw-overlay ::-webkit-scrollbar-thumb{background:color-mix(in srgb,var(--dvw-text) 20%,transparent);border:2px solid transparent;background-clip:padding-box;border-radius:6px}')
  })

  it('leaves language service installation to settings', () => {
    const workbench = read('src/client/Workbench.tsx')
    expect(workbench).not.toContain('<h2>语言未安装</h2>')
    expect(workbench).not.toContain('以后再说')
    expect(workbench).not.toContain('languageServerIdForPath(active)')
    expect(workbench).toContain('<h3>语言智能</h3>')
  })

  it('lists TypeScript with the other languages in one block', () => {
    const workbench = read('src/client/Workbench.tsx')
    expect(workbench).not.toContain('未安装。安装后会索引工作区中的 TS/JS 文件。')
    expect(workbench).toContain("内置 · {tsIntellisense ? tsIndex.state === 'loading'")
  })

  it('offers VS Code language navigation for TS/JS from settings', () => {
    const workbench = read('src/client/Workbench.tsx')
    const monaco = read('src/client/MonacoEditor.tsx')
    expect(workbench).toContain('<h3>语言智能</h3>')
    expect(workbench).toContain("changeLsp(server.id,server.installed?'uninstall':'install')")
    expect(workbench).toContain('lsp.status')
    expect(workbench).toContain('dvw-lsp-chip')
    expect(workbench).not.toContain('重新检测')
    expect(workbench).toContain("settingsSection==='language'")
    expect(workbench).not.toContain('dvw:watch-ignore')
    expect(workbench).not.toContain('<h3>文件监听</h3>')
    expect(read('src/client/typescriptProject.ts')).toContain("localStorage.getItem(TS_INTELLISENSE_KEY) === 'on'")
    expect(workbench).toContain("{tsIntellisense?'卸载':'安装'}")
    expect(workbench).toContain('monaco.editor.registerEditorOpener(')
    expect(monaco).toContain("multipleDefinitions: 'gotoAndPeek'")
    expect(monaco).toContain("alternativeDefinitionCommand: 'editor.action.goToReferences'")
    expect(monaco).toContain('parameterHints: { enabled: true, cycle: true }')
    expect(monaco).toContain('if (isIndexedModel(key))')
  })

  it('adjusts the editor font size without scaling the workbench chrome', () => {
    const workbench = read('src/client/Workbench.tsx')
    expect(workbench).toContain("localStorage.setItem('dvw:font-size'")
    expect(workbench).toContain('<span>编辑器字体大小</span>')
    expect(workbench).toContain('setTimeout(() => onChange(draft), 180)')
    expect(workbench).toContain('fontSize={fontSize}')
    expect(read('src/client/MonacoEditor.tsx')).toContain('fontSize: props.fontSize ?? 14')
    expect(read('src/client/MonacoEditor.tsx')).toContain('renderLineHighlightOnlyWhenFocus: true')
    expect(read('src/client/styles.ts')).toContain('font:13px/1.4')
  })

  it('keeps the terminal and Monaco on the same dark surfaces', () => {
    expect(read('src/client/TerminalPanel.tsx')).toContain("background: '#191a1b'")
    expect(read('src/client/TerminalPanel.tsx')).toContain('getComputedStyle(root.current).backgroundColor')
    expect(read('src/client/TerminalPanel.tsx')).toContain("yellow: '#949800'")
    expect(read('src/client/TerminalPanel.tsx')).toContain('minimumContrastRatio: 4.5')
    const monaco = read('src/client/MonacoEditor.tsx')
    expect(monaco).toContain("DARK_THEME = 'dvw-dark'")
    expect(monaco).toContain("'editor.background': '#121314'")
    expect(monaco).toContain('monacoThemeFor(props.theme)')
    expect(monaco.match(/'vs-dark'/g)?.length ?? 0).toBe(1)
    expect(read('src/client/styles.ts')).toContain('border-bottom:0;background:var(--dvw-base)}.dvw-terminal-actions')
  })

  it('offers pure-white and eye-care themes with matching surfaces', () => {
    const styles = read('src/client/styles.ts')
    const workbench = read('src/client/Workbench.tsx')
    const monaco = read('src/client/MonacoEditor.tsx')
    expect(workbench).toContain("['white','纯白']")
    expect(workbench).toContain("['eyecare','护眼']")
    expect(styles).toContain('.dvw-overlay[data-dvw-theme=white]{--dvw-base:#fff;--dvw-surface-1:#fff')
    expect(styles).toContain('.dvw-overlay[data-dvw-theme=eyecare]{--dvw-base:#f7ebc8;--dvw-surface-1:#f7ebc8')
    expect(styles).toContain('body[data-dvw-palette=white] [data-dvw-conversation-panel]')
    expect(styles).toContain('body[data-dvw-palette=eyecare] [data-dvw-conversation-panel]')
    // The DSH composer draws on --dsw-specific-input-major; leaving it white punches a white box into the yellow panel.
    expect(styles).toContain('--dsw-specific-input-major:#f7ebc8')
    expect(monaco).toContain("EYE_THEME = 'dvw-eyecare'")
    expect(monaco).toContain("'editor.background': '#f7ebc8'")
  })
})
